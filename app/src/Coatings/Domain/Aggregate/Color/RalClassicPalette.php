    /** @var array<string, RalColor>|null */
    private static ?array $index = null;

    public static function tryGet(string $code): ?RalColor
    {
        return self::index()[self::normalizeCode($code)] ?? null;
    }

    public static function require(string $code): RalColor
    {
        return self::tryGet($code)
            ?? throw new AppException(sprintf('Код RAL «%s» отсутствует в каталоге RAL Classic.', $code));
    }

    /**
     * @return list<RalColor>
     */
    public static function all(): array
    {
        return array_values(self::index());
    }

    /**
     * Поиск по фрагменту имени (регистронезависимо) или по цифрам кода.
     *
     * @return list<RalColor>
     */
    public static function search(string $query): array
    {
        $needle = trim($query);
        if ('' === $needle) {
            return [];
        }

        $nameNeedle = mb_strtolower($needle);
        $digits = preg_replace('/\D+/', '', $needle) ?? '';

        $matches = [];
        foreach (self::all() as $ral) {
            if (str_contains(mb_strtolower($ral->name), $nameNeedle)) {
                $matches[] = $ral;
                continue;
            }

            if ('' !== $digits && str_contains($ral->code, $digits)) {
                $matches[] = $ral;
            }
        }

        return $matches;
    }

    /**
     * @return array<string, RalColor>
     */
    private static function index(): array
    {
        if (null === self::$index) {
            $index = [];
            foreach (self::COLORS as [$code, $name, $hex]) {
                $index[$code] = new RalColor($code, $name, new HexColor($hex));
            }
            self::$index = $index;
        }

        return self::$index;
    }

    private static function normalizeCode(string $raw): string
    {
        $compact = preg_replace('/\s+/', '', strtoupper(trim($raw))) ?? '';

        if (preg_match('/^\d{4}$/', $compact)) {
            $compact = 'RAL'.$compact;
        }

        if (preg_match('/^RAL(\d{4})$/', $compact, $m)) {
            return 'RAL '.$m[1];
        }

        return $raw;
    }
